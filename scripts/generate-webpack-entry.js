#!/usr/bin/env node
'use strict';

/**
 * Generates webpack-entry.js from public/index.html preserving the exact
 * script execution order expected by SimplexDM's global singleton modules.
 *
 * Excludes:
 * - Third-party libraries under lib/ (Cesium, Ion SDK, XLSX)
 * - Vendor scripts under js/vendor/ (kept as standalone script tags)
 * - Early head script js/simplexThemeSync.js (kept in <head> to avoid theme flash)
 * - Existing webpack bundle files (js/bundle.*.js)
 */

const fs = require('fs');
const path = require('path');

const ROOT_DIR = path.resolve(__dirname, '..');
const DEFAULT_HTML_PATH = path.join(ROOT_DIR, 'public', 'index.html');
const DEFAULT_OUT_PATH = path.join(ROOT_DIR, 'webpack-entry.js');

/**
 * Scripts kept as separate <script src="..."> tags in index.html rather than bundled.
 */
const STANDALONE_JS_PREFIXES = ['js/vendor/', 'js/bundle.'];
const STANDALONE_JS_EXACT = new Set([
    'js/simplexThemeSync.js',
    'js/siteContentClient.js',
    'js/siteContentAdmin.js',
]);

function isBundledRendererScript(src) {
    if (!src || typeof src !== 'string') return false;
    const clean = src.split('?')[0].split('#')[0].trim();
    if (!clean.startsWith('js/')) return false;
    if (STANDALONE_JS_EXACT.has(clean)) return false;
    for (const prefix of STANDALONE_JS_PREFIXES) {
        if (clean.startsWith(prefix)) return false;
    }
    return clean.endsWith('.js');
}

/**
 * Extract ordered `js/...` script paths from index.html.
 * @param {string} html
 * @returns {string[]}
 */
function extractScriptOrder(html) {
    const ordered = [];
    const seen = new Set();
    const scriptTagRe = /<script\b[^>]*\bsrc=["']([^"']+)["'][^>]*>\s*<\/script>/gi;
    let match;
    while ((match = scriptTagRe.exec(html)) !== null) {
        const rawSrc = match[1];
        const clean = rawSrc.split('?')[0].split('#')[0].trim();
        if (!isBundledRendererScript(clean)) continue;
        if (!seen.has(clean)) {
            seen.add(clean);
            ordered.push(clean);
        }
    }
    return ordered;
}

/**
 * Generate webpack-entry.js and validate every referenced script exists on disk.
 * @param {{ htmlPath?: string, outPath?: string, publicDir?: string, silent?: boolean }} [options]
 * @returns {{ scripts: string[], missing: string[], outPath: string }}
 */
function generateWebpackEntry(options = {}) {
    const htmlPath = options.htmlPath || DEFAULT_HTML_PATH;
    const outPath = options.outPath || DEFAULT_OUT_PATH;
    const publicDir = options.publicDir || path.dirname(htmlPath);
    const silent = Boolean(options.silent);

    if (!fs.existsSync(htmlPath)) {
        throw new Error(`Template HTML not found: ${htmlPath}`);
    }

    const html = fs.readFileSync(htmlPath, 'utf8');
    const scripts = extractScriptOrder(html);
    if (scripts.length === 0) {
        throw new Error(`No renderer <script src="js/..."> tags found in ${htmlPath}`);
    }

    const missing = [];
    const valid = [];
    for (const rel of scripts) {
        const abs = path.join(publicDir, rel);
        if (!fs.existsSync(abs)) {
            missing.push(rel);
        } else {
            valid.push(rel);
        }
    }

    if (missing.length > 0) {
        throw new Error(
            `Missing renderer script(s) referenced in ${path.basename(htmlPath)}: ${missing.join(', ')}`
        );
    }

    const header = [
        '/**',
        ' * AUTO-GENERATED by scripts/generate-webpack-entry.js — DO NOT EDIT DIRECTLY.',
        ` * Preserves exact script load order from public/index.html (${valid.length} modules).`,
        ' */',
        '',
    ];

    const requires = valid.map((rel) => {
        const normalized = `./public/${rel.replace(/\\/g, '/')}`;
        return `require(${JSON.stringify(normalized)});`;
    });

    // Preserve index.html inline initialization queue in bundled builds
    const content = [...header, ...requires, ''].join('\n');
    fs.writeFileSync(outPath, content, 'utf8');

    if (!silent) {
        console.log(`✓ Generated ${path.relative(ROOT_DIR, outPath)} (${valid.length} modules in order)`);
    }

    return { scripts: valid, missing, outPath };
}

// Execute when run via CLI or required directly by webpack.config.js (unless suppressed for unit tests)
if (require.main === module || process.env.SIMPLEX_NO_AUTO_WEBPACK_ENTRY !== '1') {
    generateWebpackEntry();
}

module.exports = {
    STANDALONE_JS_EXACT,
    STANDALONE_JS_PREFIXES,
    isBundledRendererScript,
    extractScriptOrder,
    generateWebpackEntry,
};
